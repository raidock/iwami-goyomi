def check_participation_reports() -> int:
    """参加報告の判定。過去形だけを捕まえられているかを見る。"""
    bad = 0
    for t in MUST_NOT_DROP_AS_PAST_REPORT:
        v = classify(t)
        if v.bucket == "drop" and "過去の報告" in v.reason:
            print(f"  [NG] 巻き込み: {t}  ← {v.reason}")
            bad += 1
    for t, body in MUST_NOT_DROP_BY_BODY:
        v = classify(t, body)
        if v.bucket == "drop" and "過去の報告" in v.reason:
            print(f"  [NG] 本文に引っ張られた: {t}  ← {v.reason}")
            bad += 1
    for t in PAST_REPORTS:
        v = classify(t)
        if v.bucket != "drop":
            print(f"  [NG] 参加報告が残った: {t}  ← bucket={v.bucket}")
            bad += 1
    n = len(MUST_NOT_DROP_AS_PAST_REPORT) + len(MUST_NOT_DROP_BY_BODY) + len(PAST_REPORTS)
    print(f"  参加報告の判定: {n - bad}/{n} 件")
    return bad


