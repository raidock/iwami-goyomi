def main():
    tp = fp = tn = fn = 0
    review = []
    misses = []

    for t in EVENT:
        v = classify(t)
        if v.bucket == "drop":
            fn += 1
            misses.append(("見逃し", t, v.reason))
        else:
            tp += 1
            if v.bucket == "review":
                review.append(t)

    for t in NOISE:
        v = classify(t)
        if v.bucket == "drop":
            tn += 1
        else:
            fp += 1
            misses.append(("誤検出", t, v.reason))
            if v.bucket == "review":
                review.append(t)

    total = len(EVENT) + len(NOISE)
    print(f"実データ {total}件（イベント {len(EVENT)} / ノイズ {len(NOISE)}）\n")
    print(f"  取りこぼし(見逃し) : {fn} 件")
    print(f"  誤検出             : {fp} 件")
    print(f"  正しく捨てた       : {tn}/{len(NOISE)} 件")
    print(f"  正しく拾った       : {tp}/{len(EVENT)} 件")
    recall = tp / len(EVENT)
    prec = tp / (tp + fp) if (tp + fp) else 0
    print(f"\n  再現率(拾えた割合) : {recall:.0%}")
    print(f"  適合率(拾ったうち正しい割合): {prec:.0%}")
    print(f"  人間が見る件数     : {len(review)} 件（ここが1日の承認作業量）")

    if misses:
        print("\n--- 間違えたもの ---")
        for kind, t, why in misses:
            print(f"  [{kind}] {t[:44]}  ← {why}")

    print("\n--- カテゴリ判定の例 ---")
    for t in EVENT[:8]:
        v = classify(t)
        print(f"  {v.category or '(未分類)':<14} {t[:38]}")
        if v.tags:
            print(f"  {'':<14} tags: {', '.join(v.tags)}")

    # 見逃しゼロを最重要視する（公開物として取りこぼしが一番痛い）
    return 0 if fn == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
