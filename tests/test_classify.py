def check_participation_reports() -> int:
    """参加報告の判定。過去形だけを捕まえられているかを見る。"""
    bad = 0
    for t in MUST_NOT_DROP_AS_PAST_REPORT:
        v = classify(t)
        if v.bucket == "drop" and "過去の報告" in v.reason:
            print(f"  [NG] 巻き込み: {t}  ← {v.reason}")
            bad += 1
    for t, body in MUST_NOT_DROP_BY_BODY:
        v = classify(t, body)
        if v.bucket == "drop" and "過去の報告" in v.reason:
            print(f"  [NG] 本文に引っ張られた: {t}  ← {v.reason}")
            bad += 1
    for t in PAST_REPORTS:
        v = classify(t)
        if v.bucket != "drop":
            print(f"  [NG] 参加報告が残った: {t}  ← bucket={v.bucket}")
            bad += 1
    n = len(MUST_NOT_DROP_AS_PAST_REPORT) + len(MUST_NOT_DROP_BY_BODY) + len(PAST_REPORTS)
    print(f"  参加報告の判定: {n - bad}/{n} 件")
    return bad


# 「第N回」の床。**床であって加点ではない。**
# (タイトル, 期待する bucket, 何を守っているか)
SERIAL_CASES = [
    # 拾えるようになるもの（RSSに説明文がなく、催しの語彙も無い実データ）
    ("第４４回「天領さん」　（２０２６）", "review", "大田市最大の夏祭り。全角数字"),
    ("第57回浜田市美術展", "review", "会期10/3〜10/12の実在の催し"),
    # 除外語に当たるものは救わない（床の処理を入れる位置を間違えると上がる）
    ("令和8年度　第2回浜田市職員採用試験について", "drop", "職員採用は行政内部"),
    ("20260728令和8年度第6回浜田市情報公開・個人情報保護審査会", "drop", "審査会"),
    ("令和8年第2回6月定例会", "drop", "議会"),
    ("令和8年度　明るい選挙啓発ポスターコンクール（第78回）　作品募集", "drop", "選挙"),
    # すでに score 1 以上のものは動かさない（review → auto を起こさない）
    ("大盛況でした！　『夜の図書館で生演奏！　第７回かぶりもんズライブ』のご報告",
     "review", "過去の報告。加点にすると自動公開される"),
    ("第37回さざんか祭り　アトラクション参加者募集について", "auto", "元から auto"),
]


def check_serial_floor() -> int:
    """「第N回」の床が、救うものと救わないものを分けられているか。"""
    bad = 0
    for title, expect, why in SERIAL_CASES:
        v = classify(title)
        if v.bucket != expect:
            print(f"  [NG] {title[:40]} → {v.bucket}（期待 {expect}／{why}）")
            print(f"       score={v.score} {v.reason}")
            bad += 1
    # 床は1で止まること（+2 になっていないこと）を直接見る
    v = classify("第４４回「天領さん」　（２０２６）")
    if v.score != 1:
        print(f"  [NG] 床が1で止まっていない: score={v.score}")
        bad += 1
    print(f"  第N回の床: {len(SERIAL_CASES) + 1 - bad}/{len(SERIAL_CASES) + 1} 件")
    return bad


def main():
    tp = fp = tn = fn = 0
    review = []
    misses = []

    for t in EVENT:
        v = classify(t)
        if v.bucket == "drop":
            fn += 1
            misses.append(("見逃し", t, v.reason))
        else:
            tp += 1
            if v.bucket == "review":
                review.append(t)

    for t in NOISE:
        v = classify(t)
        if v.bucket == "drop":
            tn += 1
        else:
            fp += 1
            misses.append(("誤検出", t, v.reason))
            if v.bucket == "review":
                review.append(t)

    total = len(EVENT) + len(NOISE)
    print(f"実データ {total}件（イベント {len(EVENT)} / ノイズ {len(NOISE)}）\n")
    print(f"  取りこぼし(見逃し) : {fn} 件")
    print(f"  誤検出             : {fp} 件")
    print(f"  正しく捨てた       : {tn}/{len(NOISE)} 件")
    print(f"  正しく拾った       : {tp}/{len(EVENT)} 件")
    recall = tp / len(EVENT)
    prec = tp / (tp + fp) if (tp + fp) else 0
    print(f"\n  再現率(拾えた割合) : {recall:.0%}")
    print(f"  適合率(拾ったうち正しい割合): {prec:.0%}")
    print(f"  人間が見る件数     : {len(review)} 件（ここが1日の承認作業量）")

    if misses:
        print("\n--- 間違えたもの ---")
        for kind, t, why in misses:
            print(f"  [{kind}] {t[:44]}  ← {why}")

    print("\n--- カテゴリ判定の例 ---")
    for t in EVENT[:8]:
        v = classify(t)
        print(f"  {v.category or '(未分類)':<14} {t[:38]}")
        if v.tags:
            print(f"  {'':<14} tags: {', '.join(v.tags)}")

    print("\n--- 参加報告の巻き込み点検 ---")
    bad = check_participation_reports()

    print("\n--- 「第N回」の床の点検 ---")
    bad += check_serial_floor()

    # 見逃しゼロを最重要視する（公開物として取りこぼしが一番痛い）
    return 0 if fn == 0 and bad == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
