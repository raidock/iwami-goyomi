# 「第44回」「第５７回」— 繰り返し開催される催しの印。
# 全角数字と漢数字も使われる（大田市は「第４４回「天領さん」」）。
# 「第N号」（広報紙）「第N次」（総合計画）「第N期」は催しではないので回だけを見る。
# 実データ325件で測ったとき、動く2件がどちらもノイズだった。
SERIAL_EVENT_RE = re.compile(r"第\s*[0-9０-９一二三四五六七八九十百]+\s*回")

