# 参加報告。「〜に参加しました！【お礼、報告】」の型で、「様子を掲載しました」と
# 同じ終わったことの報告。機械に判断がつくので承認キューには送らない。
#
# **タイトルだけで見る。** 未来の告知の本文には「昨年は多くの方にご参加
# いただきました」がふつうに書かれていて、本文まで見ると本物の催しが消える。
# 参加報告は必ずタイトルで名乗る（説明文に引っ張られた事故と同じ構図なので、
# カテゴリ判定と同様にタイトルを信じる）。
#
# **過去形だけを捕まえる。** 「しまねふるさとフェアに出展します」は本物の
# 催しの告知で、「参加者を募集します」は EVENT_STRONG_RE の中心。
# ここは最優先で判定されるので、誤って捕まえると本物が消える。
#
# 「募集を終了します」も同じ型。肯定形（募集）が終了の文脈に埋まっているので、
# 「参加者募集」が EVENT_STRONG_RE に当たって score 7 で自動公開されていた
# （大田市「２０２６夏の山村留学」参加者募集を終了します）。
#
# **終了の対象を限定する。** 裸の「終了します」を捕まえてはいけない。
# 「この展示は8月31日をもって終了します」は催しそのものが終わる知らせで、
# 最後の機会を伝える価値がある。閉じたのが**募集の窓**のときだけ落とす。
# 住民にできることが何も残っていないのは、こちらだけ。
# **「〜ました」全般では落とせない。** 過去形でも住民にできることが残っている
# ものがある（「参加者募集を開始しました」はまだ申し込める、「オープンしました」
# はまだ行ける）。実データ322件で `ました` を当てると、募集の告知まで巻き込む。
# 捕まえるのは**行事が済んだことを名乗っている言い回し**だけ。
