def detect_kind(title: str) -> str:
    """種別を決める。**タイトルだけを見る。**

    本文まで見ると引っ張られる。三瓶山のハンモック（大田市観光協会）は
    サイト自身が「イベント期間 2026年04月01日～06月30日」と宣言している催しだが、
    RSS要約の末尾にあった **「貸出」の1語**で制度になり、`is_past()` が
    制度を見ない（設計判断1）ため、会期が終わっても「いつでも使えるもの」に
    残り続けていた。

    カテゴリをタイトル優先にしたのと同じ話（設計判断10）。設計判断13の
    「語彙には適用範囲がある」で**4回目**の同じ形になる
    （カテゴリ・過去の報告・除外語・種別）。

    タイトルに制度語があるものは変わらない（「出前講座をご利用ください」は制度のまま）。
    """
    if any(w in title for w in SEIDO_PAT):
        return "制度"
    if any(w in title for w in MOYOSHI_NOUN):
        return "催し"
    if any(w in title for w in BOSHU_PAT):
        return "募集"
    return "催し"


@dataclass
class Verdict:
    is_event: bool          # 自動採用ラインを超えたか
    score: int
    category: str | None
    tags: list[str]
    reason: str             # なぜそう判定したか（承認画面で人が見る）
    kind: str = "催し"       # 催し / 募集 / 制度

    @property
    def bucket(self) -> str:
        """auto = 自動採用 / review = 人が見る / drop = 捨てる"""
        if self.score >= 4:
            return "auto"
        if self.score >= 1:
            return "review"
        return "drop"


def decide_bucket(v: "Verdict", title: str, trust: str = "normal") -> str:
    """**どこへ入れるかの最終判断。** 仕分けの結果と情報源の性質を合わせて決める。

    ここに集めてあるのは、判断が3か所に散ると必ず食い違うため。

    1. 観光協会（`trust: high`）はしきい値を下げる（設計判断11）。
       イベント専用RSSなので、そもそも催ししか流れてこない。
       **除外語を踏んだ -10 は通さない**（入札や通行止めが流れてきたときの穴）。

    2. **人を通さず公開するなら、タイトルに根拠が要る。**
       本文は「拾う」には十分でも、「人が見ずに公開する」には足りない。
       本文は別の話題を語りうるからで、実際に踏んだ:

         「いわみスタジアム・瑞穂球場を改修します」   タイトルだけなら score 0
         RSS要約に「2030年に国民スポーツ大会が開催されます」
         と**改修の理由として**書かれていたため score 7 で自動公開された

       水道メーター事故と同じ形。**語を1つずつ潰すのは対症療法**なので、
       根拠の置き場所そのものを条件にする。

       **観光協会には課さない。** あちらは情報源そのものが根拠で、
       「8/9 鮎小屋」のようにタイトルが短い催しが普通にある（設計判断11）。
       課すと実データ173件で15件が承認待ちに移り、全部が本物だった。
       自治体だけに課せば、同じ実データで移るものは**0件**（2026-08-01 実測）。
    """
    bucket = v.bucket
    if v.score > -10 and trust == "high":
        bucket = "auto" if v.score >= 2 else "review"
    if bucket == "auto" and trust != "high" and classify(title).score <= 0:
        return "review"
    return bucket


def _hits(text: str, words) -> list[str]:
    return [w for w in words if w in text]


def _has_event_noun(text: str) -> bool:
    """催しの名詞が含まれているか（SOFT_EXCLUDE の判定に使う）。

    **`展` は外さないこと。** 素の「展」は「発展」にも当たるので
    「地域発展委員会の開催について」が承認キューに1件漏れるが、外すと
    「〇〇委員会主催　絵画展」のような本物が消える。
    取りこぼしゼロを優先して、漏れるほうを選んでいる。
    """
    upper = text.upper()
    return any(w in text or w.upper() in upper
               for w in set(EVENT_MEDIUM) | set(MOYOSHI_NOUN))


def classify(title: str, body: str = "") -> Verdict:
    text = f"{title} {body}"

    # 1. 過去の報告を最優先で落とす（イベント語を含むため）
    for pat in PAST_REPORT:
        if re.search(pat, text):
            return Verdict(False, -10, None, [], f"過去の報告と判定: {pat}")
    # 1b. 参加報告はタイトルだけで見る（本文まで見ると未来の告知を殺す）
    for pat in PAST_REPORT_TITLE:
        if re.search(pat, title):
            return Verdict(False, -10, None, [], f"過去の報告と判定: {pat}")

    # 2. 行政内部の事務を落とす
    for pat in HARD_EXCLUDE_RE:
        if re.search(pat, text):
            return Verdict(False, -10, None, [], f"除外パターン: {pat}")
    ex = _hits(text, HARD_EXCLUDE)
    if ex:
        return Verdict(False, -10, None, [], f"除外語: {', '.join(ex[:3])}")

    # 2b. 会議体だが主催者名にもなる語。**催しの名詞を伴わないときだけ落とす**
    if not _has_event_noun(text):
        soft = _hits(text, SOFT_EXCLUDE)
        if soft:
            return Verdict(False, -10, None, [],
                           f"会議体（催しの語なし）: {soft[0]}")

    # 3. 加点
    score = 0
    reasons = []
    upper = text.upper()
    m = [w for w in EVENT_MEDIUM if w in text or w.upper() in upper]

    if [p for p in EVENT_STRONG_RE if re.search(p, text)]:
        score += 4
        reasons.append("開催・募集の明示")
    elif [p for p in GENERIC_ACTION_RE if re.search(p, text)]:
        # 「行います」は催しの名詞を伴うときだけ強い根拠になる
        if m:
            score += 4
            reasons.append("催しの語＋実施表現")
        else:
            score += 1
            reasons.append("汎用の動詞のみ（催しの語なし）")

    if m:
        score += 2
        reasons.append(f"イベント語: {'/'.join(m[:2])}")
    if w := _hits(text, EVENT_WEAK):
        score += 1
        reasons.append(f"弱い手がかり: {w[0]}")

    # 3b. 「第N回」は繰り返し開催される催しの印。**床としてだけ効かせる。**
    #
    # RSSに説明文がなく、タイトルに催しの語彙もないと score 0 で落ちる。
    # 大田市最大の夏祭り「第４４回「天領さん」（２０２６）」と
    # 「第57回浜田市美術展」がこれで消えていた。
    #
    # 加点（+2）にしてはいけない。すでに score 2 のものが auto に上がり、
    # 「大盛況でした！『…第７回かぶりもんズライブ』のご報告」が自動公開される
    # （実データで確認。事故表の「参加報告」と同型）。
    # **床なので、すでに1以上のものは動かさない。**
    #
    # **タイトルだけで見る**（設計判断13）。本文の関連記事一覧にも「第N回」は並ぶ。
    # 除外語は先に評価されて早期に戻るので、ここに来る時点で
    # 「第2回浜田市職員採用試験」のような行政内部のものは残っていない。
    if score < 1 and SERIAL_EVENT_RE.search(title):
        score = 1
        reasons.append("繰り返しの催しの印: 第N回")

    # 4. カテゴリ
    # **タイトルを優先する。** 説明文まで見ると引っ張られる。
    # 「ぶどうまつり」の紹介文に「石見神楽の上演があります」とあるだけで
    # 神楽カテゴリになってしまった（2026-07 実画面）。
    category = None
    for source in (title, text):
        for name, words in CATEGORY_RULES:
            if _hits(source, words):
                category = name
                break
        if category:
            break

    # 5. タグ
    tags = [name for name, words in TAG_RULES if _hits(text, words)]

    kind = detect_kind(title)
    if kind == "制度":
        tags = tags + ["随時"]

    return Verdict(score >= 4, score, category, tags,
                   " / ".join(reasons) or "手がかりなし", kind)
